// Writes the issue's @font-face rules (src/styles/fonts.css) and the licence
// that ships beside the font files (public/assets/OFL.txt). The faces come from
// Fontsource's npm packages: Google Fonts' own woff2 files, cut into Google's
// unicode-range slices, so a page fetches only the slices holding characters it
// shows. Vite copies each file it is pointed at into dist/assets/ with a hash.
// Run it after changing a package's version or the weights below, and commit
// what it writes:
//
//   node scripts/fonts.mjs
import { readFileSync, existsSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (path) => readFileSync(new URL(path, root), "utf8");

// The family names the styles ask for, the weights and styles they use, and the
// copyright notice each file carries. A static family lists one stylesheet per
// weight and style; a variable one has a single file for every weight, declared
// once per weight as Google Fonts does, so a weight in between still matches the
// next one up (a <b> in Inter Tight is set at 800, never 700). Noto Serif SC
// takes 400 to 700 as one range: the blog sets 400 and 700, the issue 500.
const FAMILIES = [
  {
    family: "Instrument Serif", pkg: "@fontsource/instrument-serif", css: ["400.css", "400-italic.css"],
    notice: "Copyright 2022 The Instrument Serif Project Authors (https://github.com/Instrument/instrument-serif)",
  },
  {
    family: "Inter Tight", pkg: "@fontsource-variable/inter-tight", css: ["wght.css"], weights: ["400", "500", "600", "800"],
    notice: "Copyright 2022 The Inter Project Authors (https://github.com/rsms/inter-tight)",
  },
  {
    family: "JetBrains Mono", pkg: "@fontsource-variable/jetbrains-mono", css: ["wght.css"], weights: ["400", "500"],
    notice: "Copyright 2020 The JetBrains Mono Project Authors (https://github.com/JetBrains/JetBrainsMono)",
  },
  {
    family: "Shippori Mincho B1", pkg: "@fontsource/shippori-mincho-b1", css: ["700.css", "800.css"],
    notice: "Copyright 2021 The Shippori Mincho Project Authors (https://github.com/fontdasu/ShipporiMincho)",
  },
  {
    family: "Zen Kaku Gothic New", pkg: "@fontsource/zen-kaku-gothic-new", css: ["500.css", "700.css"],
    notice: "Copyright 2022 The Zen Project Authors (https://github.com/googlefonts/zen-kakugothic)",
  },
  {
    family: "Noto Serif SC", pkg: "@fontsource-variable/noto-serif-sc", css: ["wght.css"], weights: ["400 700"],
    notice: "(c) 2017-2024 Adobe (http://www.adobe.com/).",
  },
];

const field = (block, name) => block.match(new RegExp(`${name}:\\s*([^;]+);`))?.[1].trim();

// A family's slices in its package's order, each with the faces (weights,
// styles) that share its unicode-range. Where two of a family's ranges overlap,
// the face written later wins, so that order has to survive.
function slicesOf(f) {
  const slices = new Map();
  for (const sheet of f.css) {
    const text = read(`node_modules/${f.pkg}/${sheet}`);
    for (const [, block] of text.matchAll(/@font-face\s*\{([^}]*)\}/g)) {
      const file = block.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      const range = field(block, "unicode-range");
      if (!file || !range) throw new Error(`${f.pkg}/${sheet}: a face without a woff2 file or a unicode-range`);
      if (!existsSync(new URL(`node_modules/${f.pkg}/files/${file}`, root))) throw new Error(`${f.pkg}: files/${file} is missing`);
      const style = field(block, "font-style");
      if (!slices.has(range)) slices.set(range, []);
      for (const weight of f.weights ?? [field(block, "font-weight")]) slices.get(range).push({ family: f.family, pkg: f.pkg, style, weight, file });
    }
  }
  return [...slices].map(([range, faces]) => ({ range, faces }));
}

// Merges two lists of slices, keeping each list's order and putting slices with
// the same unicode-range side by side (a longest common subsequence). Shippori
// and Zen are cut alike, so their ranges repeat next to each other and gzip
// takes the copies for almost nothing: the file shrinks by about a third.
function merge(a, b) {
  const lcs = Array.from({ length: a.length + 1 }, () => new Array(b.length + 1).fill(0));
  for (let i = a.length - 1; i >= 0; i--)
    for (let j = b.length - 1; j >= 0; j--)
      lcs[i][j] = a[i].range === b[j].range ? lcs[i + 1][j + 1] + 1 : Math.max(lcs[i + 1][j], lcs[i][j + 1]);
  const out = [];
  let i = 0;
  let j = 0;
  while (i < a.length && j < b.length) {
    if (a[i].range === b[j].range) out.push({ range: a[i].range, faces: [...a[i++].faces, ...b[j++].faces] });
    else if (lcs[i + 1][j] >= lcs[i][j + 1]) out.push(a[i++]);
    else out.push(b[j++]);
  }
  return [...out, ...a.slice(i), ...b.slice(j)];
}

const version = (pkg) => JSON.parse(read(`node_modules/${pkg}/package.json`)).version;
let css = `/*
 * The issue's typefaces, served from this site. Generated by scripts/fonts.mjs
 * from these packages; do not edit by hand. Licences (SIL Open Font License 1.1)
 * in public/assets/OFL.txt, served beside the files.
${FAMILIES.map((f) => ` *   ${f.family}: ${f.pkg} ${version(f.pkg)}`).join("\n")}
 * Faces that share a unicode-range are written together, whatever their family.
 * "?no-inline" keeps Vite from pasting slices under 4 KB into the stylesheet,
 * where every page would download them, wanted or not.
 */
`;
let faces = 0;
for (const { range, faces: list } of FAMILIES.map(slicesOf).reduce(merge)) {
  for (const { family, pkg, style, weight, file } of list) {
    const italic = style === "italic" ? " font-style: italic;" : "";
    css += `@font-face { font-family: "${family}";${italic} font-weight: ${weight}; font-display: swap; src: url("${pkg}/files/${file}?no-inline") format("woff2"); unicode-range: ${range}; }\n`;
    faces++;
  }
}
writeFileSync(new URL("src/styles/fonts.css", root), css);

// One copy of the licence, after every family's notice. The packages carry the
// same OFL 1.1 text under their own copyright lines; check that they still do.
const body = (pkg) => read(`node_modules/${pkg}/LICENSE`).replace(/^[^\n]*\n+/, "");
const ofl = body(FAMILIES[0].pkg);
for (const f of FAMILIES) if (body(f.pkg) !== ofl) throw new Error(`${f.pkg}: its LICENSE is not the OFL text the others carry`);
const files = (f) => `${f.pkg.split("/")[1]}-*.woff2`;
writeFileSync(
  new URL("public/assets/OFL.txt", root),
  `The typefaces in this folder (*.woff2) are served by s1lin.tokensbeat.com
under the SIL Open Font License, Version 1.1, given in full below. They are the
files Google Fonts serves, unmodified, from the Fontsource packages.

${FAMILIES.map((f) => `${f.family} (${files(f)})\n${f.notice}`).join("\n\n")}

ascii.rest mono (ascii-rest-mono-*.woff2), a cut of JetBrains Mono for the line
and block characters, made by ascii.rest (https://ascii.rest)
${FAMILIES.find((f) => f.family === "JetBrains Mono").notice}

${ofl}`,
);
console.log(`src/styles/fonts.css: ${faces} faces of ${FAMILIES.length} families; public/assets/OFL.txt`);
